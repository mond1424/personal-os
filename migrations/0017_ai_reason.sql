-- 0017 — 모델이 **왜 그렇게 답했는지** 남긴다 (T-38)
--
-- 판정 22건 중 approve가 0이고 deny가 11이다. deny 열한 번은 네트워크 문제가 아니다 —
-- 모델이 닿았고, 판단했고, 거부했다(둘은 ai_used=1로 기록됐다). 그런데 **왜**가 없다.
-- 서버는 이유를 만들어 보내고(`VerifyResult.reason`) 기기는 파싱까지 하는데
-- `amendFire`가 나르는 목록에 없어서 그 자리에서 버려졌다.
--
-- 그래서 지금 데이터로는 이 둘을 못 가른다:
--   ① 프롬프트가 격상할 만한 상황을 안 만든다   → VERIFY_SYSTEM을 고칠 일
--   ② 그 밤들이 정말로 격상할 상황이 아니었다    → 아무것도 안 고칠 일
-- 9~11월이 §6.5의 전례를 쌓는 기간인데 세 달 내내 Level 4가 0회면
-- 12월에 읽을 것이 "개입했다"의 절반뿐이다.
--
-- ★ `ai_unavailable_reason`과 **합치지 않는다.** 뜻이 다르고 읽는 쪽이 다르다:
--
--   ai_unavailable_reason   왜 못 물어봤나      닫힌 CHECK — **기계가 센다**(12월 집계)
--   ai_reason               왜 그렇게 답했나    자유 문자열 — **사람이 읽는다**
--
-- 합치면 기계가 읽던 쪽이 깨진다 — 자유 문자열이 섞이는 순간 GLOB·IN이 뜻을 잃는다.
--
-- ★ `ai_verdict`의 CHECK를 넓히지 않는다. T-31이 그 자리에서 잡혔다:
--   0010의 CHECK를 어기면 400이 되고, 기기의 `flush()`가 400을 '재시도 무의미'로 보고
--   **발동 행을 통째로 버린다.** 관측하려던 밤의 기록이 사라진다.
--   여기서도 같은 형태로 더한다 — **더하고, 빼지 않는다.**
--
-- NULL 허용이 필수 조건이다. 옛 APK는 이 키를 안 싣고, 그 행도 살아야 한다
-- (새 칼럼을 NOT NULL로 두면 관측을 늘리려다 관측을 잃는다).
-- 과거 행도 NULL이다 — **"모른다"가 사실이다.** 소급해서 만들지 않는다.
--
-- CHECK를 두지 않는 이유: 값이 모델이 쓴 문장이라 닫을 수 있는 집합이 아니다.
-- 길이 상한도 SQL이 아니라 서버가 진다(`record()`) — CHECK 위반은 400이고,
-- 400은 위에서 말한 그 행 유실 경로다. **자르되 거부하지 않는다.**

ALTER TABLE guard_events ADD COLUMN ai_reason TEXT;
