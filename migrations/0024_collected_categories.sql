-- 0024 — 과목은 제목이 아니라 CATEGORIES 가 안다 (T-74 · ADR-037 §재검토 트리거)
--
-- 0018 이 `❌ CATEGORIES가 없다`로 남긴 칸이 2026-09-15 전수로 닫혔다.
-- ⚠️ **그때 본 것은 "없다"가 아니라 "코스 이벤트를 못 봤다"였다.** 8/17 표본은 VEVENT 하나였고
--    그것이 **사용자가 만든 개인 이벤트**다 — Moodle 은 코스 이벤트에만 강좌를 싣는다.
--    (도구의 0건이 *없다* 와 *못 봤다* 를 구별하지 않는 그 자리 — CLAUDE.md 함정 18.)
--
-- 실측 2026-09-15 — 내보내기 셋으로 수집된 5건 **전수**:
--   5 / 5 에 CATEGORIES 가 있다. 없는 건 0.
--   전자기및연습1 (2026-20\, 45004_01_U)     ← 3건
--   인간과인공지능 (2026-20\, 01702_01_U)     ← 2건   ★ 과목이 둘로 갈렸다 (표본이 n=1 과목이 아니다)
--   쉼표는 전부 `\,`(이스케이프). **이스케이프 안 된 쉼표(다중값)는 안 왔다.**
--
-- ★★ **그리고 SUMMARY 가 거짓말을 한다 — 이 칸의 존재 이유다.**
--   `벡터대수학 2주차 연습문제 제출 기한`   → 과목은 **전자기및연습1** (벡터대수학은 과제 내용이다)
--   `중간고사대체과제 기한` · `학기과제 기한` → 과목이 제목에 **아예 없다**
--   과제 이름은 교수가 짓고 CATEGORIES 는 강좌에서 자동으로 붙는다 —
--   **뒤에는 사람이 틀릴 자리가 없다.**
--
-- ★ **원문 그대로 넣는다. 쪼개지 않는다.** 과목명·학기·코드로 가르는 것은 **해석**이고
--   표시하는 쪽이 한다(0018 의 `summary` 주석과 같은 규칙).
--   언이스케이프(`\,` → `,`)는 해석이 아니라 **복원**이다 — RFC 5545 §3.3.11.
--   ⚠️ 되돌리지 않으면 저장된 값이 원문이 아니다.
