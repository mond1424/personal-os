-- 0025 — 수락한 과제가 할 일도 된다 (T-78 · 설계 §1.7)
--
-- `POST /api/collected/:id/accept` 가 `events` 행 **하나만** 만들고 있었다.
-- 그래서 과제는 *"달력에 적힌 날짜"* 로는 존재하는데 *"내가 해야 하는 일"* 로는 존재하지 않았다.
--
-- 실측 2026-09-17 (원격 D1) — 티켓 ① 확인:
--   accepted 3건(티켓은 2건이라 적었다 — 9/16 에 하나가 더 붙었다) · tasks 22 · events 35.
--   accepted 의 summary 와 제목이 같은 task: **0건.**
--   ★ 그 0이 *"없다"* 인지 *"못 봤다"* 인지는 알려진 정답을 먹여 갈랐다(함정 18) —
--     같은 꼴의 자기참조 질의가 22를 냈다. **질의는 살아 있었고 0은 진짜 0이다.**
--   events ↔ tasks 를 잇는 칸도 없었다. `collected_items.event_id` 하나뿐이다.
--
-- ★ **이 칸은 멱등을 위해 있다.** `accept` 는 이미 멱등인데(`state='accepted'` + `event_id`),
--   task 를 그 가드 밖에서 만들면 **event 는 하나인 채로 task 만 늘어난다.**
--   느린 네트워크에서 두 번 눌리는 것이 이 카드의 기본 조건이다(T-42 §할 일 ①).
--
-- ★ **`event_id` 와 같은 꼴로 둔다.** 잇는 방향을 `tasks.source_event_id` 로 뒤집을 수도 있었지만
--   그러면 *"수집에서 왔다"* 를 아는 곳이 둘이 된다 — 수락의 산물 둘은 수락한 행이 안다.
--
-- ⚠️ **이미 accepted 인 3건은 NULL 로 남는다. 소급해서 task 를 만들지 않는다**(티켓 ③).
--    *"수집된 것"* 과 *"내가 넣은 것"* 이 섞이면 원장이 거짓이 된다(T-74 §확인 절차와 같은 규칙).
--    그 셋은 이미 지난 과제다 — **판정은 다음에 수락하는 건으로 한다.**
--    ★ 그래서 `accept` 의 이른 반환은 `event_id` 만 본다. 옛 행이 그 문을 지나면
--      **오늘 task 가 생기고 그것은 오늘 넣은 것처럼 보인다.**

ALTER TABLE collected_items ADD COLUMN task_id TEXT REFERENCES tasks(id);
